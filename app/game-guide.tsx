function nextMove(s: State, target: number, first: number | null) {
  if (s.status !== "playing")
    return "結果を確認したら、評価を保存してリトライするか、別のゲームと比較しよう。";
  if (s.kind === "lost") {
    const remaining = s.known
      .slice(1)
      .filter((row) =>
        row.every((v, i) => v === null || v === bits(s.roles[0])[i]),
      ).length;
    return `公開された属性から矛盾のない候補は${remaining}人。今の選択は${names[target]}。${s.turn === 0 ? "まず紋章を選んで「全員を観察」してみよう。" : "未確認の属性を観察するか、選んだ相手を共鳴テストで確かめよう。"}`;
  }
  if (s.kind === "sync")
    return `今の任務行動は「${moves[missions[s.roles[0]][s.turn % 3]]}」。${s.score >= 3 ? `指名条件を満たした。履歴を比較し、${names[target]}を指名するかカードで相手を変えよう。` : s.exposure === 2 ? "警戒が2なので任務行動をすると監視のペナルティ。隠密を挟むか、得点を失って進めるか考えよう。" : "任務に一致する行動で得点を増やし、公開履歴で同じ周期の相手を探そう。"}`;
  if (s.kind === "dungeon")
    return s.buddy === levels[s.stage].plate
      ? `守護者が圧力板にいる。NPCへの指示を「待機」にして保持しよう。${s.key ? "探索者を出口へ移動しよう。" : "探索者を鍵のマスへ進めよう。"}`
      : "NPCへの指示を設定してから、自分の方向ボタンを押そう。探索者は鍵へ、守護者は圧力板へ向かわせよう。";
  if (s.kind === "element")
    return s.turn % 3 === 2
      ? "次は敵の大攻撃（9ダメージ）。防御すると1ダメージにできる。"
      : s.linked
        ? "合体技が解放済み。合体技で攻めつつ、大攻撃の予告には防御を合わせよう。"
        : `今の選択は${names[target]}。技を観察して自分と同じ属性か確認し、同じなら合流しよう。`;
  return first !== null
    ? `${names[first]}を選択中。つなぐ相手のカードを押そう。同じ相手との線があれば削除される。`
    : `ヒント取得済み${s.hints.length}/6人、接続${s.edges.length}/6本。${s.edges.length === 6 ? "各人の両隣と線を照合して「つながりを判定」。" : "「○○に聞く」で情報を集め、カードを2枚ずつ選んで線を引こう。"}`;
}

export function GameGuide({
  kind,
  state,
  target,
  first,
}: {
  kind: Kind;
  state: State | null;
  target: number;
  first: number | null;
}) {
  const guide = guides[kind];
  return (
    <section className="game-guide" aria-label="ルールと遊び方">
      <div className="guide-title">
        <h2>ルールと遊び方</h2>
        <span>プレイ中も、ここで確認できます</span>
      </div>
      <div className="guide-goal">
        <strong>このゲームの目的</strong>
        <p>{guide.goal}</p>
      </div>
      <div className="guide-columns">
        <div>
          <h3>操作の順番</h3>
          <ol>
            {guide.steps.map((step) => (
              <li key={step}>{step}</li>
            ))}
          </ol>
        </div>
        <div>
          <h3>画面・情報の読み方</h3>
          <p>{guide.read}</p>
          <h3>何を考えるゲーム？</h3>
          <p>{guide.decision}</p>
        </div>
      </div>
      <div className="guide-example">
        <strong>最初のプレイの具体例</strong>
        <p>{guide.example}</p>
      </div>
      <details className="guide-details" open>
        <summary>各操作の効果・勝利と敗北</summary>
        <div className="table-wrap">
          <table>
            <thead>
              <tr>
                <th>操作</th>
                <th>起きること</th>
                <th>消費</th>
              </tr>
            </thead>
            <tbody>
              {guide.actions.map(([action, effect, cost]) => (
                <tr key={action}>
                  <th scope="row">{action}</th>
                  <td>{effect}</td>
                  <td>{cost}</td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
        <p>
          <strong>勝利：</strong>
          {guide.win}
        </p>
        <p>
          <strong>敗北：</strong>
          {guide.lose}
        </p>
      </details>
      {state && (
        <aside className="guide-next" aria-live="polite">
          <strong>
            {state.status === "playing"
              ? "いま、何をすればいい？"
              : "プレイのあとに"}
          </strong>
          <p>{nextMove(state, target, first)}</p>
        </aside>
      )}
    </section>
  );
}
